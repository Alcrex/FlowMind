import { test, expect, type BrowserContext } from '@playwright/test'
import { createHmac, randomUUID } from 'node:crypto'
const secret = 'flowmind-local-development-secret-change-before-deployment-2026'
function token(id: number) {
  const header = Buffer.from(JSON.stringify({ alg: 'HS256' })).toString('base64url')
  const payload = Buffer.from(JSON.stringify({ sub: String(id), userId: id, jti: randomUUID(), exp: Math.floor(Date.now() / 1000) + 3600, iat: Math.floor(Date.now() / 1000) })).toString('base64url')
  return `${header}.${payload}.${createHmac('sha256', secret).update(`${header}.${payload}`).digest('base64url')}`
}
async function authenticate(context: BrowserContext, value: string) {
  await context.addInitScript(value => localStorage.setItem('flowmind.token', value), value)
}
test('real workflow APIs, canvas editing, Yjs convergence, cursors, snapshots and rollback', async ({ browser }) => {
  const ownerToken = token(3), memberToken = token(4)
  const a = await browser.newContext(), b = await browser.newContext()
  await authenticate(a, ownerToken); await authenticate(b, memberToken)
  const pa = await a.newPage(), pb = await b.newPage()
  const errors: string[] = []; pa.on('pageerror', ex => errors.push(ex.message)); pb.on('pageerror', ex => errors.push(ex.message))
  const api = await pa.request.post('http://localhost:8080/api/v1/workflows', { headers: { Authorization: `Bearer ${ownerToken}` }, data: { wfName: `浏览器协作 ${Date.now()}`, category: 'CODE_ASSIST', isPublic: 0 } })
  expect(api.ok()).toBeTruthy(); const id = (await api.json()).data.workflow.id
  try {
    const seeded = await pa.request.get('http://localhost:8080/api/v1/workflows/1', { headers: { Authorization: `Bearer ${ownerToken}` } })
    expect(seeded.ok()).toBeTruthy()
    expect((await seeded.json()).data.nodes).toHaveLength(4)
    await pa.request.put(`http://localhost:8080/api/v1/workflows/${id}/collaborators`, { headers: { Authorization: `Bearer ${ownerToken}` }, data: { collaboratorIds: [4] } })
    await pa.goto(`/workflow/editor/${id}`)
    await expect(pa.getByText('协同已连接', { exact: false })).toBeVisible()
    await pb.goto(`/workflow/editor/${id}`)
    await expect(pb.getByText('协同已连接', { exact: false })).toBeVisible()
    await expect(pa.locator('.flow-node')).toHaveCount(2); await expect(pb.locator('.flow-node')).toHaveCount(2)
    const input = pa.locator('.vue-flow__node[data-id="node_input_1"]')
    const inputBounds = await input.boundingBox(), stageBounds = await pa.locator('.canvas-stage').boundingBox()
    expect(inputBounds!.x).toBeGreaterThanOrEqual(stageBounds!.x)
    await pa.getByRole('button', { name: 'LL 大语言模型' }).click()
    await expect(pb.locator('.flow-node')).toHaveCount(3)
    const llmA = pa.locator('.vue-flow__node').filter({ hasText: '大语言模型' })
    const llmB = pb.locator('.vue-flow__node').filter({ hasText: '大语言模型' })
    async function wire(source: ReturnType<typeof pa.locator>, target: ReturnType<typeof pa.locator>) {
      const from = await source.locator('.vue-flow__handle.source').boundingBox(), to = await target.locator('.vue-flow__handle.target').boundingBox()
      await pa.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2)
      await pa.mouse.down(); await pa.mouse.move(to!.x + to!.width / 2, to!.y + to!.height / 2, { steps: 8 }); await pa.mouse.up()
    }
    await wire(input, llmA)
    await wire(llmA, pa.locator('.vue-flow__node[data-id="node_output_1"]'))
    await expect(pb.locator('.vue-flow__edge')).toHaveCount(2)
    await llmA.dblclick()
    const prompt = pa.getByLabel('系统提示词')
    await prompt.fill('你是浏览器测试助手')
    await pa.getByRole('button', { name: '应用配置' }).click()
    await llmB.dblclick()
    await expect(pb.getByLabel('系统提示词')).toHaveValue('你是浏览器测试助手')
    await pb.getByRole('button', { name: '关闭', exact: true }).last().click()
    const positionBefore = await llmB.getAttribute('style')
    const box = await llmA.boundingBox(); expect(box).toBeTruthy()
    await pa.mouse.move(box!.x + 70, box!.y + 30); await pa.mouse.down(); await pa.mouse.move(box!.x + 220, box!.y + 130, { steps: 8 }); await pa.mouse.up()
    await expect.poll(() => llmB.getAttribute('style')).not.toBe(positionBefore)
    const stage = await pa.locator('.canvas-stage').boundingBox()
    await pa.mouse.move(stage!.x + 100, stage!.y + 200); await pa.mouse.move(stage!.x + 150, stage!.y + 220, { steps: 3 })
    await expect(pb.locator('.remote-cursor').filter({ hasText: '顾峰鸣' })).toBeVisible()
    await pa.getByRole('button', { name: '保存新版本', exact: true }).click()
    await pa.locator('.el-message-box__input input').fill('v-browser-1')
    await pa.getByRole('button', { name: '保存版本', exact: true }).click()
    await expect(pa.getByText('版本快照已保存', { exact: true })).toBeVisible()
    // Concurrent additions must both survive in the Yjs maps.
    await Promise.all([pa.getByRole('button', { name: 'CO 代码处理' }).click(), pb.getByRole('button', { name: 'KN 知识检索' }).click()])
    await expect(pa.locator('.flow-node')).toHaveCount(5); await expect(pb.locator('.flow-node')).toHaveCount(5)
    // A membership change preserves both windows' unsaved elements.
    await pa.request.put(`http://localhost:8080/api/v1/workflows/${id}/collaborators`, { headers: { Authorization: `Bearer ${ownerToken}` }, data: { collaboratorIds: [4, 5] } })
    await expect(pa.locator('.flow-node')).toHaveCount(5); await expect(pb.locator('.flow-node')).toHaveCount(5)
    const rollback = await pa.request.post(`http://localhost:8080/api/v1/workflows/${id}/versions/rollback`, { headers: { Authorization: `Bearer ${ownerToken}` }, data: { versionTag: 'v1.0.0' } })
    expect(rollback.ok()).toBeTruthy()
    await expect(pa.locator('.flow-node')).toHaveCount(2); await expect(pb.locator('.flow-node')).toHaveCount(2)
    await expect(pa.getByText('协同已连接', { exact: false })).toBeVisible()
    await expect(pa.locator('.el-message')).toHaveCount(0)
    await expect(pa.locator('.el-loading-mask')).toHaveCount(0)
    const outputBounds = await pa.locator('.vue-flow__node[data-id="node_output_1"]').boundingBox()
    const bounds = await pa.locator('.canvas-stage').boundingBox()
    expect(outputBounds!.x + outputBounds!.width).toBeLessThanOrEqual(bounds!.x + bounds!.width)
    await pa.screenshot({ path: 'test-results/canvas.png', fullPage: true })
    await pa.goto('/workspace'); await expect(pa.getByText('我的工作流', { exact: true }).last()).toBeVisible()
    await expect(pa.locator('.el-loading-mask')).toHaveCount(0)
    await expect(pa.locator('.recent-row')).toHaveCount(2)
    await pa.screenshot({ path: 'test-results/dashboard.png', fullPage: true })
    await pa.goto('/workflows'); await expect(pa.locator('.el-table')).toBeVisible()
    await expect(pa.locator('.el-loading-mask')).toHaveCount(0)
    await expect(pa.locator('.el-table__row')).toHaveCount(2)
    await pa.screenshot({ path: 'test-results/workflows.png', fullPage: true })
    await pa.goto(`/workflow/${id}/versions`); await expect(pa.getByText('v-browser-1', { exact: true }).first()).toBeVisible()
    await expect(pa.locator('.el-loading-mask')).toHaveCount(0)
    await pa.screenshot({ path: 'test-results/versions.png', fullPage: true })
    expect(errors).toEqual([])
  } finally {
    await pa.request.delete(`http://localhost:8080/api/v1/workflows/${id}`, { headers: { Authorization: `Bearer ${ownerToken}` } })
    await a.close(); await b.close()
  }
})

test('workflow list supports UI create, metadata edit, filters, clone and delete', async ({ browser }) => {
  const context = await browser.newContext(); const ownerToken = token(3)
  await authenticate(context, ownerToken)
  const page = await context.newPage()
  const name = `UI工作流 ${Date.now()}`, renamed = name + ' 已更新'
  const ids: number[] = []
  try {
    await page.goto('/workflows?create=1')
    await page.getByLabel('工作流名称').fill(name)
    await page.getByRole('button', { name: '创建并打开画布' }).click()
    await expect(page).toHaveURL(/workflow\/editor\/\d+/)
    ids.push(Number(page.url().split('/').at(-1)))
    await expect(page.getByText('协同已连接', { exact: false })).toBeVisible()
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByLabel('工作流名称').fill(renamed)
    await page.getByRole('button', { name: '应用设置' }).click()
    await page.getByRole('button', { name: '保存画布', exact: true }).click()
    await expect(page.getByText('画布已保存', { exact: true })).toBeVisible()
    await page.goto('/workflows')
    await page.getByPlaceholder('搜索名称、描述或标签').fill(renamed)
    await page.getByRole('button', { name: '查询', exact: true }).click()
    const rows = page.locator('.el-table__row')
    await expect(rows).toHaveCount(1); await expect(rows.first()).toContainText(renamed)
    await rows.getByRole('button', { name: '克隆', exact: true }).click()
    await expect(page).toHaveURL(/workflow\/editor\/\d+/)
    ids.push(Number(page.url().split('/').at(-1)))
    await expect(page.getByRole('heading').filter({ hasText: '副本' })).toBeVisible()
    await page.goto('/workflows')
    await page.getByPlaceholder('搜索名称、描述或标签').fill(renamed)
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await expect(rows).toHaveCount(2)
    await rows.filter({ hasText: '副本' }).getByRole('button', { name: '删除', exact: true }).click()
    await page.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(rows).toHaveCount(1)
    await page.getByPlaceholder('搜索名称、描述或标签').fill('does-not-exist')
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await expect(page.getByText('暂无符合条件的工作流')).toBeVisible()
  } finally {
    for (const id of ids) await page.request.delete(`http://localhost:8080/api/v1/workflows/${id}`, { headers: { Authorization: `Bearer ${ownerToken}` } })
    await context.close()
  }
})
