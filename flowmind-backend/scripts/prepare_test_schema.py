"""Adapt the authoritative MySQL script to H2 without changing production DDL."""
from pathlib import Path
import re

backend = Path(__file__).resolve().parents[1]
sql = (backend.parent / "sql/init_flowmind.sql").read_text(encoding="utf-8-sig")
sql = re.sub(r"CREATE DATABASE[^;]*;|USE `flowmind_db`;|SET NAMES utf8mb4;", "", sql)
sql = sql.replace("SET FOREIGN_KEY_CHECKS = 0;", "SET REFERENTIAL_INTEGRITY FALSE;")
sql = sql.replace("SET FOREIGN_KEY_CHECKS = 1;", "SET REFERENTIAL_INTEGRITY TRUE;")
sql = re.sub(r"^  KEY .*\n", "", sql, flags=re.M)
sql = re.sub(r"UNIQUE KEY `([^`]+)`", r"CONSTRAINT `\1` UNIQUE", sql)
sql = re.sub(r"\) ENGINE=InnoDB[^;]*;", ");", sql)
sql = re.sub(r"\bJSON\b(?= (?:DEFAULT|NOT))", "LONGTEXT", sql)
sql = re.sub(r",\s*\)", "\n)", sql)
sql = sql.replace("DATE_ADD(NOW(), INTERVAL 14 DAY)", "DATEADD('DAY', 14, NOW())")


def unescape_literal(match):
    # Consume each MySQL escape once, preserving JSON's own escaped quotes.
    return re.sub(r"\\(.)", lambda escaped: {"n": "\n", "r": "\r", "t": "\t", "0": "\0"}.get(escaped[1], escaped[1]), match[0])


sql = re.sub(r"'(?:[^'\\]|\\.|'')*'", unescape_literal, sql)
sql += '\nCREATE ALIAS IF NOT EXISTS JSON_CONTAINS FOR "com.flowmind.platform.workflow.H2JsonFunctions.contains";\n'
(backend / "src/test/resources/schema-test.sql").write_text(
    "-- Generated by scripts/prepare_test_schema.py from ../sql/init_flowmind.sql.\n" + sql,
    encoding="utf-8",
)
